/**
 * The rerun's navigation guard (KI-029): exploration keeps its browser on the run's hosts with a CDP guard
 * (apps/worker/src/sandbox/navigation-guard.ts); the rerun's Chromium is started by `@playwright/test` in the
 * runner, so the workspace gets this fixed `global-setup.js`, which Playwright runs before any test:
 *
 * - it launches the rerun's Chromium itself (`chromium.launchServer`: headless, Chromium's sandbox on, every
 *   connection through the rerun's egress proxy, the same hardening flags), with a CDP port on loopback;
 * - it attaches to every page as it opens (`Target.setAutoAttach`, held until guarded) and pauses each document
 *   request (`Fetch`, redirect hops included): a main-frame navigation off the run's hosts, or to anything but
 *   http(s), fails with `ERR_BLOCKED_BY_CLIENT` and is appended to `navigation-blocks.jsonl`;
 * - the test connects to that browser through Playwright's own `PW_TEST_CONNECT_WS_ENDPOINT`, so the stored
 *   test and its fixed helpers are unchanged;
 * - fail closed: a page that cannot be guarded is closed, and a lost CDP connection stops the browser.
 *
 * Plain CommonJS with no run data inside: its settings come from `rerun-guard.json` (validated by the runner).
 * Private addresses stay the egress proxy's job, as in exploration.
 */

export const GLOBAL_SETUP_FILE = "global-setup.js";
export const GUARD_SETTINGS_FILE = "rerun-guard.json";
export const NAVIGATION_BLOCKS_FILE = "navigation-blocks.jsonl";

export interface GuardSettings {
  /** `http://127.0.0.1:<port>`: the rerun's egress proxy. */
  proxyUrl: string;
  /** Exact hosts, or `*.example.com` for its strict subdomains (computeAllowedHosts). */
  allowedHosts: string[];
  /** Chromium flags (RERUN_CHROMIUM_ARGS). */
  args: readonly string[];
}

const HOST_ENTRY = /^(\*\.)?[a-z0-9.:[\]-]{1,253}$/;
const LOCAL_PROXY = /^http:\/\/127\.0\.0\.1:\d{1,5}$/;

export function buildGuardSettings(input: GuardSettings): string {
  if (!LOCAL_PROXY.test(input.proxyUrl)) throw new Error(`The rerun proxy must be the local egress proxy, got ${JSON.stringify(input.proxyUrl)}`);
  const allowedHosts = input.allowedHosts.map((h) => h.trim().toLowerCase().replace(/\.$/, ""));
  if (allowedHosts.length === 0) throw new Error("The rerun needs at least one allowed host");
  for (const h of allowedHosts) if (!HOST_ENTRY.test(h)) throw new Error(`Not an allowed-host entry: ${JSON.stringify(h)}`);
  return JSON.stringify({ proxyUrl: input.proxyUrl, allowedHosts, args: [...input.args] });
}

export const GLOBAL_SETUP_SOURCE = `// Generated by the AI testing platform for one rerun: the navigation guard. Do not edit.
"use strict";
const fs = require("node:fs");
const net = require("node:net");
const path = require("node:path");
const { chromium } = require("@playwright/test");

const DOCUMENTS = { patterns: [{ urlPattern: "*", resourceType: "Document", requestStage: "Request" }] };

function freePort() {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.once("error", reject);
    srv.listen(0, "127.0.0.1", () => {
      const port = srv.address().port;
      srv.close(() => resolve(port));
    });
  });
}

function hostAllowed(host, allowed) {
  const h = host.toLowerCase().replace(/\\.$/, "");
  return allowed.some((e) => (e.startsWith("*.") ? h.endsWith("." + e.slice(2)) : h === e));
}

function blockReason(raw, allowed) {
  if (raw === "about:blank" || raw === "about:srcdoc") return null;
  let url;
  try {
    url = new URL(raw);
  } catch {
    return "TARGET_BLOCKED_BY_POLICY";
  }
  if (url.protocol !== "http:" && url.protocol !== "https:") return "TARGET_BLOCKED_BY_POLICY";
  const host = url.hostname.startsWith("[") ? url.hostname.slice(1, -1) : url.hostname;
  return hostAllowed(host, allowed) ? null : "OFF_DOMAIN_NAVIGATION";
}

async function guard(wsUrl, allowed, onBlock, onLost) {
  const ws = new WebSocket(wsUrl);
  await new Promise((resolve, reject) => {
    ws.addEventListener("open", resolve, { once: true });
    ws.addEventListener("error", () => reject(new Error("navigation guard: CDP connection failed")), { once: true });
  });
  let seq = 0;
  let closing = false;
  const pending = new Map();
  const pages = new Map();
  const send = (method, params, sessionId) =>
    new Promise((resolve, reject) => {
      const id = ++seq;
      pending.set(id, { resolve, reject });
      ws.send(JSON.stringify(Object.assign({ id, method, params: params || {} }, sessionId ? { sessionId } : {})));
    });
  const quiet = (p) => p.catch(() => undefined);
  ws.addEventListener("close", () => {
    for (const p of pending.values()) p.reject(new Error("navigation guard: CDP connection closed"));
    pending.clear();
    if (!closing) onLost();
  });
  ws.addEventListener("message", (event) => {
    const msg = JSON.parse(String(event.data));
    if (msg.id !== undefined) {
      const p = pending.get(msg.id);
      pending.delete(msg.id);
      if (p) (msg.error ? p.reject(new Error(msg.error.message)) : p.resolve(msg.result));
      return;
    }
    const params = msg.params || {};
    if (msg.method === "Target.attachedToTarget") {
      const info = params.targetInfo;
      if (info.type === "page") {
        pages.set(params.sessionId, info.targetId);
        send("Fetch.enable", DOCUMENTS, params.sessionId).then(
          () => params.waitingForDebugger && quiet(send("Runtime.runIfWaitingForDebugger", {}, params.sessionId)),
          () => quiet(send("Target.closeTarget", { targetId: info.targetId })),
        );
      } else {
        const go = params.waitingForDebugger ? quiet(send("Runtime.runIfWaitingForDebugger", {}, params.sessionId)) : Promise.resolve();
        go.then(() => quiet(send("Target.detachFromTarget", { sessionId: params.sessionId })));
      }
    } else if (msg.method === "Target.detachedFromTarget") {
      pages.delete(params.sessionId);
    } else if (msg.method === "Fetch.requestPaused") {
      const main = pages.get(msg.sessionId);
      const reason = main === undefined || params.frameId === main ? blockReason(params.request.url, allowed) : null;
      if (reason) {
        onBlock({ url: params.request.url, reason });
        quiet(send("Fetch.failRequest", { requestId: params.requestId, errorReason: "BlockedByClient" }, msg.sessionId));
      } else {
        quiet(send("Fetch.continueRequest", { requestId: params.requestId }, msg.sessionId));
      }
    }
  });
  await send("Target.setAutoAttach", { autoAttach: true, waitForDebuggerOnStart: true, flatten: true });
  return () => {
    closing = true;
    ws.close();
  };
}

module.exports = async function globalSetup() {
  const settings = JSON.parse(fs.readFileSync(path.join(__dirname, "${GUARD_SETTINGS_FILE}"), "utf8"));
  const blocks = path.join(__dirname, "${NAVIGATION_BLOCKS_FILE}");
  const port = await freePort();
  const server = await chromium.launchServer({
    headless: true,
    chromiumSandbox: true,
    proxy: { server: settings.proxyUrl },
    args: [...settings.args, "--remote-debugging-address=127.0.0.1", "--remote-debugging-port=" + port],
  });
  let stop;
  try {
    const version = await (await fetch("http://127.0.0.1:" + port + "/json/version")).json();
    stop = await guard(
      version.webSocketDebuggerUrl,
      settings.allowedHosts,
      (block) => fs.appendFileSync(blocks, JSON.stringify(block) + "\\n"),
      () => void server.kill(),
    );
  } catch (err) {
    await server.kill();
    throw err;
  }
  process.env.PW_TEST_CONNECT_WS_ENDPOINT = server.wsEndpoint();
  // kill, not close: the test has ended and its evidence is written; a graceful close costs seconds.
  return async () => {
    stop();
    await server.kill();
  };
};
`;
