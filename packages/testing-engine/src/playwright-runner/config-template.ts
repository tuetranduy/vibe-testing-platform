import { OUTPUT_DIR } from "./result-parser";

/**
 * `playwright.config.js` of a rerun workspace (Task 17, Step 4). Plain data (JSON) behind
 * `module.exports`, built from validated inputs only: the local egress proxy's URL and timeouts.
 *
 * - `retries: 0` — V1 never hides a failure behind a retry; `workers: 1`.
 * - `timeout` — the test's share of the rerun budget (the runner keeps a margin to start up and to
 *   write results, then kills the child at the budget).
 * - the JSON reporter writes `results.json` (the result parser's input).
 * - `use.proxy` — every browser connection goes through the rerun's egress proxy (D8, Ruling R31).
 *   No `bypass`: Playwright then passes `--proxy-bypass-list=<-loopback>`, so loopback is proxied too
 *   (the child never gets PLAYWRIGHT_DISABLE_FORCED_CHROMIUM_PROXIED_LOOPBACK: env allow-list).
 * - `launchOptions.chromiumSandbox: true` — Chromium's own sandbox stays on, as in exploration's
 *   browser-launcher: Playwright adds `--no-sandbox` unless this is true, and the rerun's browser
 *   loads the untrusted target site. Where no usable sandbox exists (e.g. a container without the
 *   worker's seccomp profile, infra/seccomp), Chromium fails to start and the rerun is ERRORED
 *   (Ruling R41) — never unsandboxed.
 * - trace / screenshot / video kept on failure only (the evidence of a failed criterion).
 * - bounded action / navigation timeouts, so a missing element fails that action (the later criteria
 *   are NOT_REACHED) instead of consuming the whole budget.
 */

export const CONFIG_FILE = "playwright.config.js";
export const RESULTS_FILE = "results.json";
export const SPEC_FILE = "run.spec.ts";

/** The exploration sandbox's egress hardening that applies to a Playwright-launched Chromium too. */
export const RERUN_CHROMIUM_ARGS: readonly string[] = [
  "--disable-quic",
  "--force-webrtc-ip-handling-policy=disable_non_proxied_udp",
  "--webrtc-ip-handling-policy=disable_non_proxied_udp",
  // Chromium never resolves names itself: proxied requests don't need it; anything else fails.
  "--host-resolver-rules=MAP * ~NOTFOUND, EXCLUDE 127.0.0.1",
  "--disable-background-networking",
  "--disable-component-update",
  "--disable-domain-reliability",
  "--disable-sync",
  "--no-pings",
];

export const DEFAULT_NAVIGATION_TIMEOUT_MS = 30_000;

export interface PlaywrightConfigInput {
  /** `http://127.0.0.1:<port>` — the rerun's egress proxy. */
  proxyUrl: string;
  testTimeoutMs: number;
  actionTimeoutMs: number;
  navigationTimeoutMs?: number;
  /** Assertion timeout (`expect.timeout`); Playwright's default (5 s) when omitted. */
  expectTimeoutMs?: number;
}

const LOCAL_PROXY = /^http:\/\/127\.0\.0\.1:(\d{1,5})$/;

function assertMs(name: string, value: number): void {
  if (!Number.isInteger(value) || value <= 0) throw new Error(`${name} must be a positive integer (ms), got ${value}`);
}

export function buildPlaywrightConfig(input: PlaywrightConfigInput): string {
  const port = Number(LOCAL_PROXY.exec(input.proxyUrl)?.[1] ?? 0);
  if (port < 1 || port > 65535) throw new Error(`The rerun proxy must be the local egress proxy (http://127.0.0.1:<port>), got ${JSON.stringify(input.proxyUrl)}`);
  const navigationTimeoutMs = input.navigationTimeoutMs ?? DEFAULT_NAVIGATION_TIMEOUT_MS;
  assertMs("testTimeoutMs", input.testTimeoutMs);
  assertMs("actionTimeoutMs", input.actionTimeoutMs);
  assertMs("navigationTimeoutMs", navigationTimeoutMs);
  if (input.expectTimeoutMs !== undefined) assertMs("expectTimeoutMs", input.expectTimeoutMs);

  const config = {
    testDir: ".",
    testMatch: SPEC_FILE,
    retries: 0,
    workers: 1,
    forbidOnly: true,
    timeout: input.testTimeoutMs,
    ...(input.expectTimeoutMs !== undefined ? { expect: { timeout: input.expectTimeoutMs } } : {}),
    reporter: [["json", { outputFile: RESULTS_FILE }]],
    outputDir: OUTPUT_DIR,
    use: {
      browserName: "chromium",
      headless: true,
      proxy: { server: input.proxyUrl },
      trace: "retain-on-failure",
      screenshot: "only-on-failure",
      video: "retain-on-failure",
      actionTimeout: input.actionTimeoutMs,
      navigationTimeout: navigationTimeoutMs,
      acceptDownloads: false,
      launchOptions: { chromiumSandbox: true, args: [...RERUN_CHROMIUM_ARGS] },
    },
  };
  return `// Generated by the AI testing platform for one rerun. Do not edit.\n"use strict";\nmodule.exports = ${JSON.stringify(config, null, 2)};\n`;
}
