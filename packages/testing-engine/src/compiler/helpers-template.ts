/**
 * helpers.ts of every generated workspace (Task 16): a fixed template, identical for every run, with
 * no run data inside. The generated `run.spec.ts` reads facts and compares values through it, so a
 * rerun reads and judges exactly what exploration and the verifier did:
 *
 * - reads mirror the fact reader (exploration/fact-reader.ts): whitespace-collapsed visible text
 *   (form fields: their value), the first number in that text (`parseNumber`), child count, and the
 *   children's text for lists (empty items dropped); a locator that does not match exactly one
 *   element reads null;
 * - comparisons mirror the verifier (verification/normalize.ts, rules.ts): NFKC + collapsed
 *   whitespace, case folded unless the criterion is case-sensitive; list `contains` is case- and
 *   whitespace-insensitive, list `equals` compares whole items with case kept.
 *
 * helpers-template.test.ts runs this template against the engine's own functions over the same
 * inputs (and the same page), so the two cannot drift. Browser callbacks declare no named inner
 * functions (tsx's keepNames would wrap them in a `__name(...)` call the page doesn't define).
 */
export const PRE_ACTION_HELPERS_SOURCE = `/// <reference lib="dom" />
// Generated by the AI testing platform. Fixed helpers shared by every generated test; do not edit.
import type { Locator } from "@playwright/test";

/**
 * How long a read waits for its element to be attached before it reads null. Reads inside
 * expect.poll pass 0 (no wait): the poll retries them, and a read must not outlast the poll's timeout.
 */
const READ_TIMEOUT_MS = 5_000;

const NUMBER_TOKEN = /-?\\d(?:[\\d.,'\\u2019 ]*\\d)?/;

/** First number in a text: handles 1,299.50 / 1'299.00 / 1.234,56 / 12,5. Null if none. */
export function parseNumber(text: string): number | null {
  const m = NUMBER_TOKEN.exec(text);
  if (!m) return null;
  let token = m[0].replace(/['\\u2019 ]/g, "");
  const lastDot = token.lastIndexOf(".");
  const lastComma = token.lastIndexOf(",");
  if (lastDot >= 0 && lastComma >= 0) {
    token = lastComma > lastDot ? token.replace(/\\./g, "").replace(",", ".") : token.replace(/,/g, "");
  } else if (lastComma >= 0) {
    token = /^-?\\d{1,3}(,\\d{3})+$/.test(token) ? token.replace(/,/g, "") : token.replace(/,/g, ".");
  } else if ((token.match(/\\./g) ?? []).length > 1) {
    token = token.replace(/\\./g, "");
  }
  const n = Number(token);
  return Number.isFinite(n) ? n : null;
}

/** NFKC, whitespace collapsed and trimmed (case kept). */
export function collapseText(s: string | null): string | null {
  return s === null ? null : s.normalize("NFKC").replace(/\\s+/g, " ").trim();
}

/** collapseText, lower-cased. */
export function foldText(s: string | null): string | null {
  const collapsed = collapseText(s);
  return collapsed === null ? null : collapsed.toLowerCase();
}

/** Whether a list has an item equal to (whole item, case kept) or containing (case-insensitive) the item. */
export function listContains(list: string[] | null, item: string | null, match: "equals" | "contains"): boolean {
  if (list === null || item === null) return false;
  return match === "equals"
    ? list.some((entry) => collapseText(entry) === collapseText(item))
    : list.some((entry) => (foldText(entry) ?? "").includes(foldText(item) ?? ""));
}

/** a - b, or null when either is unknown. */
export function difference(a: number | null, b: number | null): number | null {
  return a === null || b === null ? null : a - b;
}

/** A secret from the environment; the test stops if it is missing (values are never in the source). */
export function secret(value: string | undefined): string {
  if (value === undefined) throw new Error("A secret this test needs was not provided");
  return value;
}

/** Whether the locator matches exactly one element, after waiting (up to waitMs) for it to be attached. */
async function single(locator: Locator, waitMs: number): Promise<boolean> {
  if (waitMs > 0) await locator.first().waitFor({ state: "attached", timeout: waitMs }).catch(() => {});
  return (await locator.count()) === 1;
}

const collapse = (s: string) => s.replace(/\\s+/g, " ").trim();

/** Visible text (form fields: their value), whitespace-collapsed. */
export async function readText(locator: Locator, waitMs = READ_TIMEOUT_MS): Promise<string | null> {
  if (!(await single(locator, waitMs))) return null;
  const raw = await locator.evaluate((el) =>
    el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement || el instanceof HTMLSelectElement
      ? el.value
      : el instanceof HTMLElement
        ? el.innerText
        : (el.textContent ?? ""),
  );
  return collapse(raw);
}

/** The first number in the element's text. */
export async function readNumber(locator: Locator, waitMs = READ_TIMEOUT_MS): Promise<number | null> {
  const text = await readText(locator, waitMs);
  return text === null ? null : parseNumber(text);
}

/** Number of child elements. */
export async function readCount(locator: Locator, waitMs = READ_TIMEOUT_MS): Promise<number | null> {
  if (!(await single(locator, waitMs))) return null;
  return locator.evaluate((el) => el.children.length);
}

/** Each child element's text, whitespace-collapsed, empty ones dropped (no children: the lines of its text). */
export async function readTextList(locator: Locator, waitMs = READ_TIMEOUT_MS): Promise<string[] | null> {
  if (!(await single(locator, waitMs))) return null;
  const items = await locator.evaluate((el) => {
    const children = Array.from(el.children);
    return children.length > 0
      ? children.map((c) => (c instanceof HTMLElement ? c.innerText : (c.textContent ?? "")))
      : (el instanceof HTMLElement ? el.innerText : (el.textContent ?? "")).split("\\n");
  });
  return items.map(collapse).filter(Boolean);
}

/** The text of each child element itemSelector matches, else of its first match inside the child, collapsed; children without one dropped. */
export async function readItemTexts(locator: Locator, itemSelector: string, waitMs = READ_TIMEOUT_MS): Promise<string[] | null> {
  if (!(await single(locator, waitMs))) return null;
  const items = await locator.evaluate(
    (el, sel) =>
      Array.from(el.children)
        .map((c) => (c.matches(sel) ? c : c.querySelector(sel)))
        .map((n) => (n === null ? "" : n instanceof HTMLElement ? n.innerText : (n.textContent ?? ""))),
    itemSelector,
  );
  return items.map(collapse).filter(Boolean);
}
`;

/** Keep the previous reviewed template accepted for saved suites created before KI-049. */
export const ACTION_HELPERS_V1_SOURCE = PRE_ACTION_HELPERS_SOURCE.replace(
  'import type { Locator } from "@playwright/test";',
  'import type { Locator, Page, Request } from "@playwright/test";',
) + `
/**
 * Subscribe before a click, then await the returned function before the next step (KI-049).
 * Only the main frame's fetch/XHR requests matter; iframe traffic and images cannot hold the test.
 * A failed click ends the test and closes its page; a settled click always removes its listeners.
 */
export function trackActionRequests(page: Page, timeoutMs = 5_000): () => Promise<void> {
  const pending = new Set<Request>();
  const frame = page.mainFrame();
  const onRequest = (request: Request) => {
    try {
      if ((request.resourceType() === "fetch" || request.resourceType() === "xhr") && request.frame() === frame) pending.add(request);
    } catch {
      // Service worker requests have no frame.
    }
  };
  const onDone = (request: Request) => { pending.delete(request); };
  page.on("request", onRequest);
  page.on("requestfinished", onDone);
  page.on("requestfailed", onDone);
  return async () => {
    try {
      await page.waitForLoadState("load", { timeout: 10_000 }).catch(() => {});
      const deadline = Date.now() + timeoutMs;
      while (pending.size > 0 && Date.now() < deadline) {
        await new Promise((resolve) => setTimeout(resolve, Math.min(50, Math.max(0, deadline - Date.now()))));
      }
    } finally {
      page.off("request", onRequest);
      page.off("requestfinished", onDone);
      page.off("requestfailed", onDone);
    }
  };
}
`;

/**
 * The current template (KI-058, KI-060): a click also waits for the route code (scripts) it loads and for its requests
 * to stay settled briefly, like the executor, and `readNumberOrZero` reads a counter the way the verifier does in a
 * numeric_delta. Tests saved with ACTION_HELPERS_V1_SOURCE or PRE_ACTION_HELPERS_SOURCE stay accepted.
 */
export const HELPERS_SOURCE = ACTION_HELPERS_V1_SOURCE.replace(
  `/**
 * Subscribe before a click, then await the returned function before the next step (KI-049).
 * Only the main frame's fetch/XHR requests matter; iframe traffic and images cannot hold the test.`,
  `/**
 * Subscribe before a click, then await the returned function before the next step (KI-049, KI-058).
 * The main frame's fetch/XHR, script and document requests matter (a route change loads its code, then
 * its data), until none has been pending for quietMs; iframe traffic and images cannot hold the test.`,
).replace(
  "export function trackActionRequests(page: Page, timeoutMs = 5_000): () => Promise<void> {",
  "export function trackActionRequests(page: Page, timeoutMs = 5_000, quietMs = 300): () => Promise<void> {",
).replace(
  'if ((request.resourceType() === "fetch" || request.resourceType() === "xhr") && request.frame() === frame) pending.add(request);',
  'if (["fetch", "xhr", "script", "document"].includes(request.resourceType()) && request.frame() === frame) pending.add(request);',
).replace(
  `      const deadline = Date.now() + timeoutMs;
      while (pending.size > 0 && Date.now() < deadline) {
        await new Promise((resolve) => setTimeout(resolve, Math.min(50, Math.max(0, deadline - Date.now()))));
      }`,
  `      const deadline = Date.now() + timeoutMs;
      let quietSince = Date.now();
      for (;;) {
        const now = Date.now();
        if (pending.size > 0) quietSince = now;
        if (now >= deadline || now - quietSince >= quietMs) break;
        await new Promise((resolve) => setTimeout(resolve, Math.min(50, Math.max(0, deadline - now))));
      }`,
) + `
/** A counter's number: the first number in its text, 0 when it shows none (an empty cart's badge, KI-060). */
export async function readNumberOrZero(locator: Locator, waitMs = READ_TIMEOUT_MS): Promise<number | null> {
  const text = await readText(locator, waitMs);
  return text === null ? null : (parseNumber(text) ?? 0);
}
`;

