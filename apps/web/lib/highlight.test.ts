// @vitest-environment node
import { describe, expect, it } from "vitest";
import { highlightLines } from "./highlight";

const generated = `// Generated by the AI testing platform from a discovered flow. Do not edit.
import { expect, test } from "@playwright/test";
import data from "./run-data.json";

test("discovered flow", async ({ page }) => {
  await page.goto(data.targetUrl);
  await page.getByRole("button", { name: data.locators.loc5.name, exact: true }).click();
  await test.step("[AC-1] " + data.criteria["AC-1"].statement, async () => {
    expect.soft(fact1, message).not.toBeNull();
  });
});
`;

const rejoin = (lines: ReturnType<typeof highlightLines>) => lines.map((l) => l.map((t) => t.value).join("")).join("\n");

describe("highlightLines", () => {
  it("highlights a generated test without losing or changing any text", () => {
    const lines = highlightLines(generated);
    expect(rejoin(lines)).toBe(generated);
    expect(lines).toHaveLength(generated.split("\n").length);
    const types = new Set(lines.flat().map((t) => t.type));
    expect(types).toContain("keyword");
    expect(types).toContain("string");
    expect(types).toContain("comment");
    expect(lines[1]![0]).toEqual({ type: "keyword", value: "import" });
  });

  it.each([
    ["a multi-line template literal", "const s = `line one\nline ${two}\nthree`;\n"],
    ["a block comment", "/* a\n * b\n */\nconst x = 1;"],
    ["a regex", "expect(page).toHaveURL(/\\/cart\\?id=\\d+/);"],
    ["markup", 'const s = "<script>alert(1)</script>";'],
    ["an empty source", ""],
    ["windows line endings", "const a = 1;\r\nconst b = 2;\r\n"],
  ])("is lossless for %s", (_name, source) => {
    expect(rejoin(highlightLines(source))).toBe(source);
  });
});
